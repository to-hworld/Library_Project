-- 도서관 회원
create table MEMBER(
    ID VARCHAR(10) PRIMARY KEY,
    PASS VARCHAR(10) NOT NULL,
    NAME VARCHAR(10) NOT NULL,
    REG_DATE DATETIME DEFAULT NOW() NOT NULL,
    PHONE_NO VARCHAR(11) NOT NULL,
    EMAIL VARCHAR(30) DEFAULT NULL,
    REG_LIB VARCHAR(10) NOT NULL,
    AGREE CHAR(1) DEFAULT 'Y',
    CONSTRAINT MEMBER_REQ_LIB_FK FOREIGN KEY (REQ_LIB) REFERENCES LIBRARY(LIB_NAME),
    CONSTRAINT MEMBER_NAME_CHECK CHECK (REGEXP_LIKE(NAME,'^[^[:space:]]+$')),
    CONSTRAINT MEMBER_PHONE_NO_CHECK CHECK (LENGTH(PHONE_NO) <= 11),
    CONSTRAINT MEMBER_AGREE_CHECK CHECK (AGREE IN ('Y','N')),
    CONSTRAINT MEMBER_ID_CHECK CHECK (REGEXP_LIKE(ID,'^[^[:punct:][:space:]]+$')),
    CONSTRAINT MEMBER_PASS_CHECK CHECK (REGEXP_LIKE(PASS,'^[^[:punct:][:space:]]+$')),
    CONSTRAINT MEMBER_EMAIL_CHECK CHECK (REGEXP_LIKE(EMAIL,'^[^[:punct:][:space:]]+@[^[:punct:][:space:]@]+\\.[^[:punct:][:space:]@]+(\\.[^[:punct:][:space:]@]+)*$'))
);

