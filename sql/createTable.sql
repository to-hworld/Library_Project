-- 소장 도서
create table LIBRARY_BOOK(
    ISBN INT(15) PRIMARY KEY,
    TITLE VARCHAR(20) NOT NULL,
    PUBLISHER VARCHAR(10) NOT NULL,
    PUB_DATE DATE NOT NULL,
    AUTHOR VARCHAR(10) NOT NULL,
    CHECK_OUT CHAR(1) DEFAULT 'N',
    DUE_DATE DATE,
    HOLDING_LIB VARCHAR(10) NOT NULL,
    CATE VARCHAR(10) NOT NULL,
    LOC INT(10) NOT NULL,
    IMAGE_URL VARCHAR(2048) default NULL,
    CONSTRAINT LIBRARY_BOOK_HOLDING_LIB_FK FOREIGN KEY (HOLDING_LIB) REFERENCES LIBRARY(LIB_NAME),
    CONSTRAINT LIBRARY_BOOK_CATE_FK FOREIGN KEY (CATE) REFERENCES CATEGORY(CATE_NO),
    CONSTRAINT LIBRARY_BOOK_LOC_FK FOREIGN KEY (LOC) REFERENCES BOOK_LOC(LOC_NO),
    CONSTRAINT LIBRARY_BOOK_CHECK_OUT_CHECK CHECK (CHECK_OUT IN ('Y','N')),
    CONSTRAINT LIBRARY_BOOK_ISBN_CHECK CHECK (ISBN >= 0),
    CONSTRAINT LIBRARY_BOOK_TITLE_CHECK CHECK (REGEXP_LIKE(TITLE,'^[^[:space:]]+$')),
    CONSTRAINT LIBRARY_BOOK_PUBLISHER_CHECK CHECK (REGEXP_LIKE(PUBLISHER,'^[^[:space:]]+$')),
    CONSTRAINT LIBRARY_BOOK_AUTHOR_CHECK CHECK (REGEXP_LIKE(AUTHOR,'^[^[:space:]]+$'))
);

